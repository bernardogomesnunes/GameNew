import assert from 'node:assert/strict';
import * as THREE from 'three';
import { SkyMist, mistLayout } from '../src/render/SkyMist.js';
import { FLOOR, ISLAND_R } from '../src/world/skyKingdom.js';
import { BEACON_NEAR } from '../src/render/SkyBeacon.js';
const layout = mistLayout();
assert.deepEqual(layout, mistLayout());
assert.equal(layout.bank.length + layout.wisps.length, 64);
assert.ok(layout.bank.every(p => p.y + p.h / 2 < FLOOR - 30));
assert.ok(layout.wisps.every(p => p.y < FLOOR && Math.hypot(p.x, p.z) < ISLAND_R * 1.05));
console.log('PASS deterministic cloud bank below island and mist around rim');
const scene = new THREE.Scene(), mist = new SkyMist(scene);
assert.equal(scene.children.length, 1);
assert.ok(mist.mesh.isInstancedMesh);
assert.equal(mist.material.transparent, false);
const at = { x: 5000, z: -5000 }, eye = { x: 5000, z: -5000 }, colour = new THREE.Color(0x778899);
mist.update(at, eye, colour);
assert.equal(mist.mesh.visible, true);
assert.equal(mist.mesh.position.x, at.x);
assert.equal(mist.mesh.position.z, at.z);
assert.ok(mist.material.color.equals(colour));
console.log('PASS mist uses one opaque instanced mesh and follows day colour');
mist.update(at, { x: at.x + BEACON_NEAR + 1, z: at.z }, colour);
assert.equal(mist.mesh.visible, false);
mist.update(null, eye, colour);
assert.equal(mist.mesh.visible, false);
mist.enabled = false;
mist.update(at, eye, colour);
assert.equal(mist.mesh.visible, false);
console.log('PASS mist hides outside island range, absent island and disabled graphics');
