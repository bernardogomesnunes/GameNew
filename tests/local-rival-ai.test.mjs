import assert from 'node:assert/strict';
import { chooseRivalStrategies } from '../server/localBattleAI.js';
import { LocalRivalAI } from '../src/duilt/LocalRivalAI.js';
import { Rivals } from '../src/duilt/Rivals.js';
const choices={rivals:[{id:0,stance:'pressure'},{id:1,stance:'guard'},{id:2,stance:'rebuild'}]};
const snapshot={rivals:new Rivals().list};
const fake=async(url,options)=>({ok:true,json:async()=>url.endsWith('/models')?{data:[{id:'test-chat-model'}]}:{choices:[{message:{content:JSON.stringify(choices)}}]}});
assert.deepEqual(await chooseRivalStrategies(snapshot,{fetcher:fake}),choices);
console.log('PASS LM Studio adapter uses compatible endpoints and validates strategies');
await assert.rejects(()=>chooseRivalStrategies(snapshot,{fetcher:async()=>({ok:true,json:async()=>({choices:[{message:{content:'{"rivals":[{"id":0,"stance":"destroy"}]}'}}]})}),model:'test'}),/Invalid model strategy/);
console.log('PASS arbitrary or malformed model actions cannot enter Battle');
const battle=new Rivals();battle.localAI=true;
const ai=new LocalRivalAI({fetcher:async()=>({ok:true,json:async()=>choices})});await ai.tick(battle);
assert.equal(battle.list[0].tactic,'pressure');assert.equal(Rivals.fromJSON(battle.toJSON()).localAI,true);
assert.equal(Rivals.fromJSON(battle.toJSON()).list[1].tactic,'guard');
ai.dispose();
console.log('PASS rival strategies persist, remain bounded, and controller disposes');
const fallback=new LocalRivalAI({fetcher:async()=>{throw Error('offline');}});await fallback.tick(battle);
assert.ok(battle.list.every(r=>r.tactic===undefined));fallback.dispose();
console.log('PASS unavailable model restores normal strategies');
