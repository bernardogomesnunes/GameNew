import assert from 'node:assert/strict';
import { World } from '../src/world/World.js';
import { ChunkGen } from '../src/world/ChunkGen.js';
import { skyAt } from '../src/world/skyLocation.js';
import { skyTerrainReady } from '../src/core/optionalFeatures.js';
import { captureWorldSnapshot, completeWorldSnapshot, restoreWorldSnapshot } from '../src/storage/WorldSnapshot.js';
import { generateTerrainChunk, terrainConfig, prepareTerrain } from '../src/world/terrainPayload.js';

assert.equal(skyTerrainReady(), false);
const gen = new ChunkGen({ seed: 3 });
gen.sky = true;
gen.skyCut = new Set([1]);
const world = new World({ gen, height: gen.height });
const at = skyAt(gen), cx = at.x >> 4, cz = at.z >> 4;
const captured = captureWorldSnapshot(world, { minX: at.x, maxX: at.x, minZ: at.z, maxZ: at.z });
assert.equal(world.chunks.size, 0);
await completeWorldSnapshot(captured);
assert.equal(skyTerrainReady(), true, 'snapshot fallback awaits optional terrain before filling a missing Sky chunk');
assert.equal(world.chunks.size, 0, 'preparing a snapshot cannot generate terrain into the live world');
const restored = restoreWorldSnapshot(captured);
const config = terrainConfig(world);
await prepareTerrain(config);
const workerLike = generateTerrainChunk(config, cx, cz);
const original = world.getChunk(cx, cz);
assert.deepEqual(workerLike.data, original.data);
assert.deepEqual(restored.getChunk(cx, cz).data, original.data);
assert.deepEqual(workerLike.surface, original.surface);
assert.deepEqual(workerLike.biomes, original.biomes);
assert.deepEqual([...restored.gen.skyCut], [1]);
console.log('PASS deferred Sky snapshot and worker preparation preserve terrain bytes, surface/biomes and cut-chain flags');
