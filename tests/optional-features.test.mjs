import assert from 'node:assert/strict';
import { createFeatureLoader, ensureSkyTerrain, skyTerrainReady } from '../src/core/optionalFeatures.js';
import { ChunkGen } from '../src/world/ChunkGen.js';
import { World } from '../src/world/World.js';
import { skyAt } from '../src/world/skyLocation.js';

let release, calls = 0;
const load = createFeatureLoader(() => { calls++; return new Promise(resolve => { release = resolve; }); });
const first = load(), second = load();
assert.equal(first, second, 'concurrent callers share the import');
await Promise.resolve();
release({ ready: true });
assert.deepEqual(await first, { ready: true });
assert.equal(calls, 1);
assert.equal(await load(), await first);
let attempts = 0;
const retry = createFeatureLoader(async () => { if (++attempts === 1) throw new Error('offline'); return 'ready'; });
await assert.rejects(retry(), /offline/);
assert.equal(await retry(), 'ready');
assert.equal(attempts, 2);
console.log('PASS optional imports deduplicate and retry after failure');

const { FeatureScope } = await import('../src/core/FeatureScope.js');
const scope = new FeatureScope();
let finish, installed = false;
const pending = scope.run(() => new Promise(resolve => { finish = resolve; }), () => { installed = true; });
await Promise.resolve();
scope.cancel();
finish('old world');
assert.equal(await pending, false);
assert.equal(installed, false);
console.log('PASS superseded feature loads cannot install into a newer world');

assert.equal(skyTerrainReady(), false, 'ordinary terrain must not load the Sky city');
const gen = new ChunkGen({ seed: 3 });
gen.sky = true;
const world = new World({ gen, height: gen.height });
const at = skyAt(gen), cx = at.x >> 4, cz = at.z >> 4;
assert.throws(() => world.getChunk(cx, cz), /Sky terrain is not ready/);
assert.equal(world.hasChunk(cx, cz), false, 'failed generation must not cache an incomplete island');
await ensureSkyTerrain();
assert.equal(skyTerrainReady(), true);
const chunk = world.getChunk(cx, cz);
assert.ok(chunk.get(at.x & 15, at.y - 1, at.z & 15), 'retry generates the island surface');
assert.ok(gen.skyCache?.count > 0);
console.log('PASS Sky generation waits for readiness and recovers without cached partial terrain');
