import assert from 'node:assert/strict';
import { WriteQueue } from '../src/net/WriteQueue.js';
let now = 0;
const waits = [], order = [];
const queue = new WriteQueue({ intervalMs: 250, maxPending: 2, now: () => now, sleep: async ms => { waits.push(ms); now += ms; } });
let release;
const one = queue.run(async () => { order.push('first'); await new Promise(resolve => { release = resolve; }); });
const two = queue.run(async () => { order.push('second'); return 2; });
await assert.rejects(queue.run(() => 3), /Too many writes/);
await Promise.resolve();
assert.deepEqual(order, ['first']);
release(); await one;
assert.equal(await two, 2);
assert.deepEqual(order, ['first', 'second']);
assert.deepEqual(waits, [250]);
await assert.rejects(queue.run(() => { throw new Error('failed'); }), /failed/);
assert.equal(await queue.run(() => 4), 4);
console.log('PASS client writes run serially, spaced apart, bounded, and recover after failure');

const { NeonTransport } = await import('../src/net/NeonTransport.js');
let queued = 0, sent = 0;
const transport = new NeonTransport({}, { baseUrl: 'https://fake.invalid', writeQueue: { run: task => { queued++; return task(); } } });
transport.sendNow = async () => { sent++; };
await transport.send('/test', {method:'GET'});
await transport.send('/test', {method:'POST'});
await transport.send('/test', {method:'PATCH'});
await transport.send('/test', {method:'DELETE'});
assert.equal(queued, 3);
assert.equal(sent, 4);
console.log('PASS Neon transport queues all write methods while reads bypass pacing');
