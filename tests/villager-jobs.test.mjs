import assert from 'node:assert/strict';
import { VillagerJobs } from '../src/duilt/VillagerJobs.js';
import { Inventory } from '../src/items/Inventory.js';
import { World } from '../src/world/World.js';
const world = new World({sizeX:48,sizeZ:32,height:24});
for(let x=0;x<48;x++)for(let z=0;z<32;z++)world.setBlock(x,0,z,2);
const inventory=new Inventory();inventory.add('planks',12);
const hall={id:1,type:'work_hall',valid:true,region:{minX:1,maxX:3,minY:1,maxY:4,minZ:1,maxZ:3}};
const store={id:2,type:'storehouse',valid:true,region:{minX:22,maxX:25,minY:1,maxY:4,minZ:1,maxZ:4},store:new Inventory()};
const structures={list:()=>[hall,store],storeFor:s=>s.store??null};
const person={id:0,x:3.5,y:1,z:4.5,homeId:3,workId:2,hungry:false};
const settlers={people:[person]};
const completed=[];
let jobs = new VillagerJobs({world,settlers,structures,inventory,onBuildComplete:job=>completed.push(job.id)});
assert.equal(jobs.assign(0,'builder',1).ok,true);
assert.equal(person.workId,null);
const plan={name:'Wall',type:'house',region:{minX:12,maxX:14,minY:1,maxY:1,minZ:7,maxZ:7},changes:[12,13,14].map(x=>({x,y:1,z:7,prev:0,next:7}))};
const queued=jobs.enqueueBuild(plan);
assert.equal(queued.ok,true);
assert.equal(inventory.countOf('planks'),9);
jobs.tick(.1);
assert.equal(world.getBlock(12,1,7),0);
for(let n=0;n<1000;n++)jobs.tick(.1);
assert.equal(world.getBlock(14,1,7),7);
assert.equal(completed.length,1);
assert.ok(person.x>8);
console.log('PASS builders walk and place paid blocks incrementally');
const plan2={...plan,changes:[{x:18,y:1,z:9,prev:0,next:7},{x:19,y:1,z:9,prev:0,next:7}]};
const queued2=jobs.enqueueBuild(plan2);assert.equal(queued2.ok,true);
const save=jobs.toJSON();
jobs=new VillagerJobs({world,settlers,structures,inventory});jobs.loadJSON(save);
assert.equal(jobs.cancelBuild(queued2.job.id).ok,true);
assert.equal(inventory.countOf('planks'),9);
console.log('PASS queued materials survive reload and unspent materials refund on cancel');
assert.equal(jobs.deposit(1,'planks',6).moved,6);
assert.equal(inventory.countOf('planks'),3);
assert.equal(jobs.assign(0,'hauler',1).ok,true);
for(let n=0;n<1600;n++)jobs.tick(.1);
assert.equal(store.store.countOf('planks'),6);
assert.equal(jobs.supplyForHall(1).countOf('planks'),0);
console.log('PASS haulers pick up actual hall supplies and walk to store them');
assert.equal(jobs.assign(0,'builder',99).ok,false);
assert.equal(jobs.enqueueBuild({changes:[{x:6,y:1,z:6,prev:0,next:7}]}).ok,true);
person.hungry=true;
for(let n=0;n<500;n++)jobs.tick(.1);
assert.equal(world.getBlock(6,1,6),0);
console.log('PASS missing halls cannot assign jobs and hungry workers pause');
// Cargo is removed at pickup, survives saving, then arrives exactly once.
const haulBag=new Inventory();haulBag.add('stone',20);
const courier={id:7,x:3.5,y:1,z:4.5,hungry:false};
const haulSettlers={people:[courier]};
store.store.slots.fill(null);
let courierJobs=new VillagerJobs({world,settlers:haulSettlers,structures,inventory:haulBag});
courierJobs.deposit(1,'stone',20);courierJobs.assign(7,'hauler',1);
for(let n=0;n<100&&!courierJobs.assignment(7).carrying;n++)courierJobs.tick(.1);
assert.equal(courierJobs.assignment(7).carrying.count,20);
assert.equal(courierJobs.supplyForHall(1).countOf('stone'),0);
const cargoSave=courierJobs.toJSON();
courierJobs=new VillagerJobs({world,settlers:haulSettlers,structures,inventory:haulBag});courierJobs.loadJSON(cargoSave);
for(let n=0;n<1200;n++)courierJobs.tick(.1);
assert.equal(store.store.countOf('stone'),20);
assert.equal(courierJobs.assignment(7).carrying,null);
console.log('PASS carried cargo saves and is delivered once after loading');
// A changed site must not overwrite a player's subsequent edits.
person.hungry=false;
const safeJobs=new VillagerJobs({world,settlers,structures,inventory});
safeJobs.assign(0,'builder',1);
const protectedPlan={changes:[{x:30,y:1,z:12,prev:0,next:7}]};
const safe=safeJobs.enqueueBuild(protectedPlan);assert.equal(safe.ok,true);
world.setBlock(30,1,12,3);
for(let n=0;n<1000;n++)safeJobs.tick(.1);
assert.equal(world.getBlock(30,1,12),3);
assert.match(safe.job.reason,/site changed/);
console.log('PASS later edits stop construction instead of being overwritten');
const blockedJobs=new VillagerJobs({world,settlers,structures,inventory,canPlace:()=>false});
const before=inventory.countOf('planks');
assert.equal(blockedJobs.enqueueBuild({changes:[{x:8,y:1,z:8,prev:0,next:7}]}).ok,false);
assert.equal(inventory.countOf('planks'),before);
console.log('PASS protected placement is rejected before paying materials');
// Full bags retain the unspent escrow until the player can collect it.
const tiny=new Inventory({slots:1});tiny.add('planks',2);
const returns=new VillagerJobs({world,settlers,structures,inventory:tiny});
const order=returns.enqueueBuild({changes:[{x:33,y:1,z:13,prev:0,next:7},{x:34,y:1,z:13,prev:0,next:7}]});
tiny.add('stone',500);
assert.equal(returns.cancelBuild(order.job.id).remaining.planks,2);
const refundSave=returns.toJSON();
const resumed=new VillagerJobs({world,settlers,structures,inventory:tiny});resumed.loadJSON(refundSave);
tiny.remove('stone',500);
assert.equal(resumed.collectRefund(order.job.id).ok,true);
assert.equal(tiny.countOf('planks'),2);
assert.equal(resumed.collectRefund(order.job.id).ok,true);
assert.equal(tiny.countOf('planks'),2);
console.log('PASS full-bag cancellation preserves refundable escrow through saving');
