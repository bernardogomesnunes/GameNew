import assert from 'node:assert/strict';
import { Mobs } from '../src/world/Mobs.js';
import { MOBS_BY_ID } from '../src/config/mobs.js';
const mobs = new Mobs({ world: {}, rand: () => 0.8 });
mobs.groundAt = () => 5;
const cow = () => mobs.make(MOBS_BY_ID.get('cow'), 0, 5, 0);
const player = { x: 50, y: 5, z: 50 };
const m = cow(); m.facing = Math.PI * 2 - 0.1; m.target = { x: 0.1, z: 10 }; m.speed = 1;
mobs.move(m, 0.01);
assert.ok(Math.abs(m.facing - (Math.PI * 2 - 0.1)) < 0.05, 'turn gradually across angle seam');
console.log('PASS roaming turns gradually across angle seam');
const a = cow(), b = cow(); b.x = 12; a.timer = 0; mobs.list = [a, b];
mobs.think(a, 0.1, player);
assert.ok(a.target.x > 0, 'separated herd member walks toward a companion');
assert.ok(Math.hypot(a.target.x - a.x, a.target.z - a.z) <= 7, 'regrouping keeps short routes');
console.log('PASS herd regrouping uses short routes toward companions');
const owned = cow(); owned.owned = true; mobs.list.push(owned);
mobs.think(owned, 0.1, player);
assert.equal(owned.target, null);
console.log('PASS owned animals keep waiting behaviour');
const apart = cow(), penned = cow(); penned.x = 12; penned.penId = 'other'; apart.timer = 0;
mobs.list = [apart, penned]; mobs.think(apart, 0.1, player);
assert.ok(apart.target.x < 0, 'unrelated pens do not attract wild herds');
console.log('PASS regrouping ignores animals from another pen');
const led = cow(), friend = cow(); friend.x = -12; mobs.list = [led, friend];
mobs.think(led, 0.1, { x: 5, y: 5, z: 0 }, true);
assert.ok(led.target.x > 0, 'food overrides herd regrouping');
console.log('PASS food lure takes priority over regrouping');
const wall = cow(); wall.target = { x: 10, z: 10 }; wall.speed = 1; wall.facing = 0;
mobs.groundAt = (x, z) => x > 0 ? null : 5;
mobs.move(wall, 0.1);
assert.ok(wall.z > 0 && wall.x === 0);
assert.equal(wall.facing, 0, 'faces actual slide direction');
console.log('PASS wall sliding turns toward actual movement');
